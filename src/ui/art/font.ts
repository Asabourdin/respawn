export const GLYPH_H = 7

export function glyph(ch: string): string[] {
  return G[ch.toUpperCase()] ?? G['?']
}

/** Pixel runs for a string: [x, y, w] in logical px (1 px letter spacing). */
export function textRuns(text: string): { runs: [number, number, number][]; w: number; h: number } {
  const runs: [number, number, number][] = []
  let x = 0
  for (const ch of text) {
    const g = glyph(ch)
    const gw = g[0].length
    for (let y = 0; y < g.length; y++) {
      let start = -1
      for (let i = 0; i <= gw; i++) {
        const on = i < gw && g[y][i] === '#'
        if (on && start < 0) start = i
        if (!on && start >= 0) {
          runs.push([x + start, y, i - start])
          start = -1
        }
      }
    }
    x += gw + 1
  }
  return { runs, w: Math.max(0, x - 1), h: GLYPH_H }
}

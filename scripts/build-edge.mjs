// Bundles the runtime-agnostic server (server/edge-entry.ts + every npm dependency) into one ESM
// file for the Supabase Edge Function (Deno). No Node built-ins are allowed in the bundle.
//
//   node scripts/build-edge.mjs
//
// Output: supabase/functions/respawn-ai/bundle.js
import { build } from 'esbuild'
import { statSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outfile = path.join(root, 'supabase/functions/respawn-ai/bundle.js')

await build({
  entryPoints: [path.join(root, 'server/edge-entry.ts')],
  outfile,
  bundle: true,
  format: 'esm',
  // "browser" picks the fetch-based builds of the SDKs (no node:* imports); Deno runs them as-is.
  platform: 'browser',
  mainFields: ['module', 'main'],
  conditions: ['worker', 'browser', 'import', 'default'],
  target: 'es2022',
  sourcemap: false,
  minify: true,
  // Keep class names: error mapping reads err.name (SDK error classes).
  keepNames: true,
  legalComments: 'none',
  define: { 'process.env.NODE_ENV': '"production"' },
  banner: { js: '// Generated by scripts/build-edge.mjs from server/edge-entry.ts. Do not edit.' },
  logLevel: 'info',
})

const kb = Math.round(statSync(outfile).size / 1024)
console.log(`edge bundle ready: ${path.relative(root, outfile)} (${kb} KB)`)
